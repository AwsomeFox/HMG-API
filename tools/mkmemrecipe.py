#!/usr/bin/env python3
"""mkmemrecipe.py - a memory recipe (hmgapi.engine.MemRecipe) from a (stock, patched)
library pair whose patched build carries extra code in a new segment.

usage: mkmemrecipe.py <id> <device-path> <stock> <patched> --code START [--table ADDR:COUNT]
                      [--context N] [--desc "text"]

  --code START     file offset in <patched> where the added code starts; it runs to the
                   end of the PT_LOAD holding it (that segment's file offset = its vaddr)
  --table A:N      N 32-bit entries at vaddr A, each relative to A, that the added code
                   uses to reach the library: re-pointed (rel32) wherever the code lands.
                   Entries pointing inside the added code move with it and stay as they are.

Changes in the stock code segment become patch lines, or branch lines when the new bytes
are a Thumb-2 b.w into the added code (its verify region then has no fixed "after", "-").
The ELF header and program headers (file-only changes) are left out: in memory they
don't matter. The recipe holds no stock bytes: hashes of verify regions, the bytes we
write, and the added code (ours, not the manufacturer's).
"""
import argparse, hashlib, struct, sys

ap = argparse.ArgumentParser()
ap.add_argument("id"); ap.add_argument("path"); ap.add_argument("stock"); ap.add_argument("patched")
ap.add_argument("--code", required=True, type=lambda x: int(x, 0))
ap.add_argument("--table")
ap.add_argument("--context", type=int, default=16)
ap.add_argument("--desc", default="")
a = ap.parse_args()
s = open(a.stock, "rb").read(); p = open(a.patched, "rb").read()
md5 = lambda b: hashlib.md5(b).hexdigest()


def loads(b):
    phoff, = struct.unpack_from("<I", b, 0x1c); phnum, = struct.unpack_from("<H", b, 0x2c)
    out = []
    for k in range(phnum):
        t, off, va, pa, fsz, msz, fl, al = struct.unpack_from("<8I", b, phoff + 32 * k)
        if t == 1:
            out.append((off, va, fsz, fl))
    return out


text_end = loads(s)[0][2]                  # the stock code segment (offset 0, vaddr 0)
seg = [l for l in loads(p) if l[0] <= a.code < l[0] + l[2]]
if not seg or seg[0][0] != seg[0][1]:
    sys.exit("--code isn't in a PT_LOAD whose file offset is its vaddr")
seg_start, seg_end = a.code, seg[0][0] + seg[0][2]
code = p[seg_start:seg_end]


def bw_target(at, b):
    """the target of a Thumb-2 b.w (T4) at vaddr at, or None"""
    hw1, hw2 = struct.unpack_from("<HH", b)
    if hw1 & 0xf800 != 0xf000 or hw2 & 0xd000 != 0x9000:
        return None
    sbit = (hw1 >> 10) & 1; imm10 = hw1 & 0x3ff; j1 = (hw2 >> 13) & 1; j2 = (hw2 >> 11) & 1; imm11 = hw2 & 0x7ff
    i1 = 1 - (j1 ^ sbit); i2 = 1 - (j2 ^ sbit)
    off = (sbit << 24) | (i1 << 23) | (i2 << 22) | (imm10 << 12) | (imm11 << 1)
    if sbit:
        off -= 1 << 25
    return at + 4 + off


diff = [i for i in range(0x34, text_end) if s[i] != p[i]]
runs = []
for i in diff:
    if runs and i - runs[-1][1] <= 4:
        runs[-1][1] = i
    else:
        runs.append([i, i])

print(f"# {a.desc}" if a.desc else f"# {a.id}")
print(f"# generated by mkmemrecipe.py from stock {md5(s)} -> patched {md5(p)} (memory only: hmgapi.engine.MemRecipe)")
print(f"id {a.id}")
print(f"file {a.path}")
lines = []
for lo, hi in runs:
    at = lo & ~1
    t = bw_target(at, p[at:at + 4]) if hi < at + 4 else None
    vlo, vhi = max(0x34, lo - a.context), min(text_end - 1, hi + a.context)
    if t is not None and seg_start <= t < seg_end:
        print(f"verify {vlo:#x} {vhi - vlo + 1} {md5(s[vlo:vhi+1])} -")
        lines.append(f"branch {at:#x} {t - seg_start:#x}")
    else:
        print(f"verify {vlo:#x} {vhi - vlo + 1} {md5(s[vlo:vhi+1])} {md5(p[vlo:vhi+1])}")
        lines.append(f"patch {lo:#x} {p[lo:hi+1].hex()}")
print(f"segment {seg_start:#x} {code.hex()}")
if a.table:
    ta, n = a.table.split(":"); ta = int(ta, 0); n = int(n, 0)
    for k in range(n):
        v, = struct.unpack_from("<i", p, ta + 4 * k)
        target = ta + v
        if seg_start <= (target & ~1) < seg_end:
            continue                      # inside the added code: moves with it
        print(f"rel32 {ta + 4 * k - seg_start:#x} {ta - seg_start:#x} {target:#x}")
for l in lines:
    print(l)
